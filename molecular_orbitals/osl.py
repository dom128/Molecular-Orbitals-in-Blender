"""Specialize one MO to straight-line OSL. No parameter arrays, sampling, or cutoff."""

from collections import defaultdict
import math
from .model import BOHR_ANGSTROM


def number(value):
    if not math.isfinite(float(value)):
        raise ValueError("Cannot generate OSL from nonfinite constants")
    text = format(float(value), ".17g")
    return text if "." in text or "e" in text else text + ".0"


def specialized_terms(wavefunction, orbital="HOMO", spin="alpha"):
    """Fold MO, contraction, normalization, and angular weights into each Gaussian.

    Only exactly zero terms are removed. Identical center/exponent pairs share one
    exponential, including SP contractions. No coefficient threshold approximation.
    """
    index = wavefunction.select(orbital, spin)
    groups = defaultdict(lambda: defaultdict(float))
    for ao, coefficient in zip(wavefunction.aos, wavefunction.orbitals[spin].coefficients[:, index]):
        for exponent, weight in zip(ao.exponents, ao.weights):
            for powers, factor in ao.polynomial.items():
                groups[(ao.center, float(exponent))][powers] += float(coefficient * weight * factor)
    return {key: {p: v for p, v in polynomial.items() if v != 0.0}
            for key, polynomial in groups.items() if any(v != 0.0 for v in polynomial.values())}


def monomial(powers, variables):
    factors = [name for name, power in zip(variables, powers) for _ in range(power)]
    return " * ".join(factors) or "1.0"


def generate_osl(wavefunction, orbital="HOMO", spin="alpha", bohr_in_blender=BOHR_ANGSTROM):
    if not math.isfinite(bohr_in_blender) or bohr_in_blender <= 0:
        raise ValueError("bohr_in_blender must be positive and finite")
    index = wavefunction.select(orbital, spin)
    terms = specialized_terms(wavefunction, index, spin)
    lines = ["// SPDX-License-Identifier: GPL-3.0-only",
             "// Direct LCAO evaluation; generated by molecular-orbitals-osl.",
             f"// {spin} MO {index + 1}; r in Bohr; psi in bohr^(-3/2).",
             '#include "stdosl.h"', "", "float evaluate_mo(point r_bohr)", "{", "    float psi = 0.0;"]
    for center in sorted({key[0] for key in terms}):
        variables = [f"{axis}{center}" for axis in "xyz"]
        for axis, variable, coordinate in zip(range(3), variables, wavefunction.coordinates[center]):
            lines.append(f"    float {variable} = r_bohr[{axis}] - ({number(coordinate)});")
        lines.append(f"    float r2_{center} = " + " + ".join(f"{v} * {v}" for v in variables) + ";")
        for (at, exponent), polynomial in sorted(terms.items()):
            if at != center:
                continue
            angular = " + ".join(f"({number(c)}) * {monomial(p, variables)}" for p, c in sorted(polynomial.items()))
            lines.append(f"    psi += exp(-({number(exponent)}) * r2_{center}) * ({angular});")
    lines += ["    return psi;", "}", "", "shader molecular_orbital(",
              f"    float BohrInBlender = {number(bohr_in_blender)},",
              "    float Density = 2.0,", "    float Emission = 1.0,", "    float Absorption = 0.25,",
              "    float Threshold = 0.0,", "    color Positive = color(0.07, 0.45, 1.0),",
              "    color Negative = color(1.0, 0.12, 0.03),", "    output float Amplitude = 0.0,",
              "    output float Probability = 0.0,", "    output closure color PA = 0,",
              "    output closure color PD = 0)", "{",
              '    point r_bohr = transform("object", P) / max(BohrInBlender, 1.0e-12);',
              "    Amplitude = evaluate_mo(r_bohr);", "    Probability = Amplitude * Amplitude;",
              "    color phase_color = Amplitude >= 0.0 ? Positive : Negative;",
              "    color inverse_color = color(1.0) - phase_color;",
              "    float visible = abs(Amplitude) >= max(Threshold, 0.0) ? 1.0 : 0.0;",
              "    closure color volume = max(Emission, 0.0) * phase_color * emission()",
              "                         + max(Absorption, 0.0) * inverse_color * absorption();",
              "    PA = max(Density, 0.0) * visible * abs(Amplitude) * volume;",
              "    PD = max(Density, 0.0) * visible * Probability * volume;", "}", ""]
    return "\n".join(lines)
